class LLMStudent(BaseModel):
    full_name: str = Field(min_length=5, max_length=40)
    programme: Literal["B.Tech CSE", "B.Tech ECE"]
    batch_year: Literal[2024, 2025]
    cgpa: float = Field(ge=5.0, le=9.8)

    @field_validator("full_name")
    @classmethod
    def _letters_only(cls, v: str) -> str:
        v = " ".join(v.split())
        if not all(ch.isalpha() or ch == " " for ch in v) or " " not in v:
            raise ValueError("full_name must be a first name and surname using letters only")
        return v


class LLMStudentBatch(BaseModel):
    """Structured-output schema. Items are re-validated one by one as LLMStudent so a single
    bad row cannot discard the whole reply."""
    students: list[dict[str, Any]]


def render_prompts() -> tuple[str, str]:
    system = (PROMPT_DIR / "student_generation_system.txt").read_text(encoding="utf-8").strip()
    user = (PROMPT_DIR / "student_generation_user.txt").read_text(encoding="utf-8").strip()
    groups = "\n".join(f'- programme "{p}", batch_year {b}: {STUDENTS_PER_GROUP} students'
                       for p in PROGRAMMES for b in sorted(BATCH_SEMESTER))
    return system, user.replace("<<GROUPS>>", groups)


def draft_with_llm(*, client: Any, max_calls: int = 3) -> tuple[dict[tuple[str, int], list[LLMStudent]], dict[str, Any]]:
    """Ask the LLM for names/CGPA. ``client`` is an llm.LLMClient. Bad rows are rejected and
    counted, LLM failures are recorded; neither raises, because missing slots are filled
    deterministically afterwards."""
    from llm.openai_client import LLMError  # local import keeps --mode deterministic dependency-free
    system, user = render_prompts()
    accepted: dict[tuple[str, int], list[LLMStudent]] = {(p, b): [] for p in PROGRAMMES for b in BATCH_SEMESTER}
    seen_names: set[str] = set()
    rejections: list[dict[str, Any]] = []
    errors: list[str] = []
    calls = tokens = 0
    for _ in range(max_calls):
        if all(len(v) >= STUDENTS_PER_GROUP for v in accepted.values()):
            break
        try:
            result = client.generate_structured(system, user, LLMStudentBatch)
        except LLMError as exc:
            errors.append(f"{exc.code}: {exc}")
            calls += 1
            if exc.code in ("llm_config_error", "llm_api_error", "llm_timeout"):
                break  # not worth repeating
            continue
        calls += result.llm_calls
        tokens += result.total_tokens
        for i, item in enumerate(result.parsed.students):
            try:
                row = LLMStudent.model_validate(item)
            except ValidationError as exc:
                rejections.append({"index": i, "reason": exc.errors()[0]["msg"][:100]})
                continue
            key = row.full_name.casefold()
            group = (row.programme, row.batch_year)
            if key in seen_names:
                rejections.append({"index": i, "reason": "duplicate full_name"})
            elif len(accepted[group]) >= STUDENTS_PER_GROUP:
                rejections.append({"index": i, "reason": "group quota already filled"})
            else:
                seen_names.add(key)
                accepted[group].append(row)
    report = {"mode": "openai" if not client.mock else "openai-mock", "model": client.model_name,
              "llm_calls": calls, "tokens": tokens,
              "rows_accepted": sum(len(v) for v in accepted.values()),
              "rows_rejected": len(rejections), "rejection_reasons": _tally(r["reason"] for r in rejections),
              "call_errors": errors,
              "prompt_sha256": hashlib.sha256((system + "\n\n" + user).encode()).hexdigest()}
    return accepted, report


def _tally(items) -> dict[str, int]:
    out: dict[str, int] = {}
    for it in items:
        out[it] = out.get(it, 0) + 1
    return dict(sorted(out.items()))


