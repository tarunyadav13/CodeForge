def _split_marks(total: int) -> tuple[int, int]:
    internal = min(40, round(total * 0.4))
    return internal, total - internal


def _result_row(sid: str, course: str, session: str, exam_type: str, total: int, result: str) -> dict[str, Any]:
    internal, external = _split_marks(total)
    return dict(student_id=sid, course_code=course, exam_session=session, exam_type=exam_type,
                internal_marks=internal, external_marks=external, total_marks=total,
                max_marks=MAX_MARKS, result=result)


def _derive_backlogs(rows: list[dict[str, Any]]) -> int:
    by_course: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for r in rows:
        by_course[r["course_code"]].append(r)
    count = 0
    for attempts in by_course.values():
        attempts.sort(key=lambda r: (session_sort_key(r["exam_session"]), 0 if r["exam_type"] == "REGULAR" else 1))
        if attempts[-1]["result"] in BACKLOG_RESULTS:
            count += 1
    return count


def _unique_names(rng: random.Random, n: int, taken: set[str]) -> list[str]:
    names: list[str] = []
    while len(names) < n:
        name = f"{rng.choice(FIRST_NAMES)} {rng.choice(LAST_NAMES)}"
        if name.casefold() not in taken:
            taken.add(name.casefold())
            names.append(name)
    return names


def build_dataset(seed: int = DEFAULT_SEED,
                  llm_rows: Optional[dict[tuple[str, int], list[LLMStudent]]] = None) -> dict[str, Any]:
    rng = random.Random(seed)
    taken: set[str] = set()
    for rows in (llm_rows or {}).values():
        taken.update(r.full_name.casefold() for r in rows)

    # slots in a fixed order -> IDs S1001..S1036
    slots: list[tuple[str, int]] = [(p, b) for p in PROGRAMMES for b in sorted(BATCH_SEMESTER)
                                    for _ in range(STUDENTS_PER_GROUP)]
    llm_pool = {k: list(v) for k, v in (llm_rows or {}).items()}
    students: list[dict[str, Any]] = []
    llm_used = 0
    for i, (prog, batch) in enumerate(slots):
        sid = f"S{FIRST_STUDENT_NUMBER + i}"
        draft = llm_pool.get((prog, batch), [])
        if draft:
            d = draft.pop(0)
            name, cgpa = d.full_name, round(d.cgpa, 2)
            llm_used += 1
        else:
            name = _unique_names(rng, 1, taken)[0]
            cgpa = round(rng.uniform(5.2, 9.6), 2)
        if cgpa in (CGPA_CUTOFF, round(CGPA_CUTOFF - 0.01, 2)):
            cgpa = round(cgpa + 0.37, 2)  # keep boundary values exclusive to the tagged edge students
        students.append(dict(student_id=sid, full_name=name, programme=prog, batch_year=batch,
                             current_semester=BATCH_SEMESTER[batch], cgpa=cgpa, active_backlogs=0))

    attendance: list[dict[str, Any]] = []
    results: list[dict[str, Any]] = []
    tags: dict[str, list[str]] = defaultdict(list)
    for s in students:
        sid, prog = s["student_id"], s["programme"]
        spec = EDGE.get(sid, {})
        for tag in spec.get("tags", []):
            tags[tag].append(sid)
        if "cgpa" in spec:
            s["cgpa"] = spec["cgpa"]
        courses = PROGRAMME_COURSES[prog]

        # attendance
        missing = spec.get("att_missing", set())
        for code in courses:
            if missing == "ALL" or code in missing:
                rng.random()  # keep the random stream aligned
                continue
            if code in spec.get("att", {}):
                held, attended = spec["att"][code]
            else:
                held = rng.choice([36, 40, 45, 50])
                attended = int(held * rng.uniform(0.62, 0.98))
            attendance.append(dict(student_id=sid, course_code=code, classes_held=held, classes_attended=attended))

        # results
        mode = spec.get("results")
        rows: list[dict[str, Any]] = []
        if isinstance(mode, list):
            rows = [_result_row(sid, *r) for r in mode]
        elif mode == "NONE":
            rows = []
        else:
            force_pass = mode == "PASS_ONLY"
            for code in courses[:2]:
                if not force_pass and rng.random() < 0.10:
                    rows.append(_result_row(sid, code, "2025-DEC", "REGULAR", rng.randint(20, PASS_MARK_PCT - 1), "FAIL"))
                else:
                    total = max(PASS_MARK_PCT, min(95, int(rng.gauss(66, 11))))
                    rows.append(_result_row(sid, code, "2025-DEC", "REGULAR", total, "PASS"))
        results.extend(rows)
        s["active_backlogs"] = _derive_backlogs(rows)

    for s in students:
        n = s["active_backlogs"]
        if n >= 2 and s["student_id"] not in EDGE:
            tags["multiple_active_backlogs_random"].append(s["student_id"])
        if n == 1 and s["student_id"] not in EDGE:
            tags["single_backlog_random"].append(s["student_id"])
    students.sort(key=lambda r: r["student_id"])
    attendance.sort(key=lambda r: (r["student_id"], r["course_code"]))
    results.sort(key=lambda r: (r["student_id"], r["course_code"], session_sort_key(r["exam_session"]), r["exam_type"]))

    return dict(
        students=students, attendance=attendance, results=results,
        courses=[dict(zip(COLUMNS["courses"], c)) for c in COURSES],
        rule_registry=[dict(r) for r in RULES], source_register=[dict(s) for s in SOURCES],
        edge_case_students={k: sorted(v) for k, v in sorted(tags.items())},
        llm_rows_used=llm_used,
    )


def _write_csv(path: Path, table: str, rows: list[dict[str, Any]]) -> str:
    with path.open("w", encoding="utf-8", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=COLUMNS[table], lineterminator="\n")
        writer.writeheader()
        for row in rows:
            writer.writerow({c: ("" if row.get(c) is None else row.get(c)) for c in COLUMNS[table]})
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write_dataset(dataset: dict[str, Any], out_dir: Path, *, seed: int, llm_report: Optional[dict[str, Any]]) -> dict[str, Any]:
    out_dir.mkdir(parents=True, exist_ok=True)
    hashes = {t: _write_csv(out_dir / f"{t}.csv", t, dataset[t]) for t in COLUMNS}
    students = dataset["students"]
    group_sizes = defaultdict(int)
    for s in students:
        group_sizes[f"{s['programme']} | {s['batch_year']}"] += 1
    pct = [a["classes_attended"] * 100 / a["classes_held"] for a in dataset["attendance"]]
    report = {
        "generator": "scripts/gen_data.py", "seed": seed, "reference_as_of_date": REFERENCE_AS_OF_DATE,
        "mode": "openai" if llm_report else "deterministic",
        "llm": llm_report,
        "counts": {"students": len(students), "courses": len(dataset["courses"]),
                   "attendance_rows": len(dataset["attendance"]), "result_rows": len(dataset["results"]),
                   "rules": len(dataset["rule_registry"]), "source_rows": len(dataset["source_register"]),
                   "students_with_llm_drafted_name_and_cgpa": dataset["llm_rows_used"]},
        "students_per_programme_batch": dict(sorted(group_sizes.items())),
        "attendance_pct": {"min": round(min(pct), 2), "mean": round(sum(pct) / len(pct), 2), "max": round(max(pct), 2)},
        "cgpa": {"min": min(s["cgpa"] for s in students), "max": max(s["cgpa"] for s in students)},
        "edge_case_students": dataset["edge_case_students"],
        "csv_sha256": hashes,
    }
    (out_dir / "generation_report.json").write_text(json.dumps(report, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return report


