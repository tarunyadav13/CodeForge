    parser.add_argument("--out", default=str(ROOT / "data" / "synthetic"), help="output directory")
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED)
    parser.add_argument("--mode", choices=("deterministic", "openai"), default="deterministic",
                        help="openai needs OPENAI_API_KEY (or MOCK_LLM=true for an offline dry run)")
    parser.add_argument("--max-calls", type=int, default=3, help="max LLM calls in openai mode")
    args = parser.parse_args(argv)

    llm_rows, llm_report = None, None
    if args.mode == "openai":
        from llm.openai_client import LLMClient, LLMConfigError
        try:
            client = LLMClient()
        except LLMConfigError as exc:
            print(f"ERROR: {exc}", file=sys.stderr)
            return 2
        llm_rows, llm_report = draft_with_llm(client=client, max_calls=args.max_calls)
        print(f"LLM drafting ({llm_report['model']}): {llm_report['rows_accepted']} rows accepted, "
              f"{llm_report['rows_rejected']} rejected, {llm_report['llm_calls']} call(s); "
              f"missing slots are filled deterministically.")
        for err in llm_report["call_errors"]:
            print(f"  LLM problem: {err}", file=sys.stderr)
    dataset = build_dataset(args.seed, llm_rows)
    report = write_dataset(dataset, Path(args.out), seed=args.seed, llm_report=llm_report)
    c = report["counts"]
    print(f"Wrote {c['students']} students, {c['courses']} courses, {c['attendance_rows']} attendance rows, "
          f"{c['result_rows']} result rows, {c['rules']} rules to {args.out}")
    return 0


