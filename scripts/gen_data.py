"""Generate the synthetic student dataset (Annex C schema) as CSV files.

    python scripts/gen_data.py --out data/synthetic                 # deterministic, no LLM needed
    python scripts/gen_data.py --out data/synthetic --mode openai   # LLM drafts names + CGPA (needs OPENAI_API_KEY)

Then load and validate (PowerShell or any shell):

    python scripts/load_students.py --dir data/synthetic --db data/student_services.db
    python scripts/validate.py --db data/student_services.db

How the data is produced
* Student IDs (S1001-S1036), course codes, rules and every boundary value are produced by
  code from a fixed seed. LLMs cannot be trusted to hit "exactly 80.00%" or "exactly 6.50",
  so the edge cases are injected deterministically and tagged in generation_report.json.
* ``--mode openai`` asks an OpenAI model (Responses API, prompts in prompts/, saved verbatim and read
  from disk) for fictional names and CGPA values. The reply is schema-validated, then checked
  row by row with Pydantic, and anything invalid is rejected and counted. Missing slots are
  filled by the deterministic generator. Rejections are recorded as "what the LLM got wrong".
* Same seed + same mode = byte-identical CSVs in deterministic mode.
* Reserved judge IDs (S9000-S9999) and JDG* course codes are never produced.

The fixture rules/source rows use FIX-* document IDs and synthetic=Y. They are placeholders
that let the tools run until real documents are chosen; repoint rule_registry.source_doc_id
at the real Source Register rows when they exist.
"""
